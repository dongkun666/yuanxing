# 收集每个模块的函数
module_funcs = {}
for mod, fnames in MODULES.items():
    items = []
    for fname in fnames:
        if fname not in funcs:
            print(f'  WARN: {fname} not found')
            continue
        s = funcs[fname]
        e = func_end[fname]
        items.append((s, e, fname))
    # 按行号排序
    items.sort()
    module_funcs[mod] = items

# 输出统计
print('=== 模块函数块 ===')
for mod, items in module_funcs.items():
    print(f'\n  {mod} ({len(items)} 函数):')
    total_lines = sum(e - s + 1 for s, e, _ in items)
    print(f'    总行数: {total_lines}')
    for s, e, n in items[:6]:
        print(f'    L{s:4d}-L{e:4d} {n} ({e-s+1} 行)')
    if len(items) > 6:
        print(f'    ... +{len(items)-6} more')

# 收集 main.js 保留的函数
all_mod_funcs = set()
for items in module_funcs.values():
    for _, _, n in items:
        all_mod_funcs.add(n)

main_funcs = [(s, e, n) for n, s in funcs.items() if n not in all_mod_funcs]
main_funcs.sort()
print(f'\n  main.js 保留 {len(main_funcs)} 函数:')
total_main = sum(e - s + 1 for s, e, _ in main_funcs)
