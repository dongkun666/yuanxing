"""拆 script.js: 用函数列表 + 顺序拼接 (非连续)
避免大段切片包含其他模块的代码
"""
import re
from pathlib import Path

ROOT = Path(r'E:\元枢法智前端\yuanxing')
src_file = ROOT / 'assets' / 'js' / 'script.js'
src = src_file.read_text(encoding='utf-8')
lines = src.split('\n')
total = len(lines)

# 找每个 function 起始行
func_re = re.compile(r'^\s*function\s+(\w+)\s*\(', re.MULTILINE)
funcs = {}  # name -> start_line (1-based)
for m in func_re.finditer(src):
    funcs[m.group(1)] = src[:m.start()].count('\n') + 1

# 找每个 function 结束行 (匹配花括号)
def find_func_end(name, start):
    """从 start 行找配对花括号结束行 (1-based, 含)"""
    depth = 0
    seen_open = False
    for i in range(start - 1, total):
        line = lines[i]
        for ch in line:
            if ch == '{':
                depth += 1
                seen_open = True
            elif ch == '}':
                depth -= 1
                if seen_open and depth == 0:
                    return i + 1
    return total

func_end = {n: find_func_end(n, s) for n, s in funcs.items()}

