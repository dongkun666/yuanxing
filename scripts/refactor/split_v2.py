# 写文件
def write_module(name, items, header):
    out = ROOT / 'assets' / 'js' / name
    parts = [header, '']
    parts.append('// Auto-generated by module_split.py - DO NOT EDIT IN PLACE')
    parts.append('// Edit the function in its module, then re-run the split script.')
    parts.append('')
    parts.append('(function() {')
    parts.append('    "use strict";')
    parts.append('')
    for s, e, n in items:
        # 取函数体 (s..e 1-based, 包含)
        body = '\n'.join(lines[s-1:e])
        parts.append(body)
        parts.append('')
    parts.append('})();')
    out.write_text('\n'.join(parts), encoding='utf-8')
    print(f'  ✓ {name}: {(out.stat().st_size/1024):.1f} KB')

